//go:build ignore

// gen_kernels writes scan_unrolled.go: the search kernels of 1 to maxUnrolled
// error levels, with the state of each level in a variable of its own (the
// compiler keeps them in registers). Run it with go generate.
//
// A variant without the allow mask, for the patterns that have no #, was tried
// and dropped: one operation less per level, but the arm64 compiler of Go 1.27
// then swaps two registers at each turn of the loop and lengthens the chain of
// dependencies, and the kernels came out 15 to 40 % slower.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
)

const maxUnrolled = 8

func main() {
	var b bytes.Buffer
	b.WriteString("// Code generated by gen_kernels.go; DO NOT EDIT.\n\npackage obidnapat\n\n")

	b.WriteString("// runUnrolled runs the kernel written out for the number of error levels of the\n")
	b.WriteString("// pattern; it reports false when there is none.\n")
	b.WriteString("func (c *compiled) runUnrolled(dst [][3]int, text []byte, base int, st *state) ([][3]int, bool) {\n\tswitch c.levels {\n")
	for l := 1; l <= maxUnrolled; l++ {
		fmt.Fprintf(&b, "\tcase %d:\n\t\treturn c.run%d(dst, text, base, st), true\n", l, l)
	}
	b.WriteString("\t}\n\treturn dst, false\n}\n")

	for l := 1; l <= maxUnrolled; l++ {
		fmt.Fprintf(&b, "\nfunc (c *compiled) run%d(dst [][3]int, text []byte, base int, st *state) [][3]int {\n", l)
		for i := 0; i <= l; i++ {
			fmt.Fprintf(&b, "\tr%d := st[%d]\n", i, i)
		}
		b.WriteString("\tm, end, allow, off, n := &c.mask, c.end, c.allow, c.offset(base), len(c.positions)\n")
		b.WriteString("\tfor j, b := range text {\n\t\tmk := m[b]\n")
		for i := l; i >= 1; i-- {
			fmt.Fprintf(&b, "\t\tr%d = (((r%d << 1) | 1) & mk) | (((r%d << 1) | 1) & allow)\n", i, i, i-1)
		}
		b.WriteString("\t\tr0 = ((r0 << 1) | 1) & mk\n")
		fmt.Fprintf(&b, "\t\tif r%d&end != 0 {\n\t\t\te := %d\n\t\t\tswitch {\n", l, l)
		for i := 0; i < l; i++ {
			fmt.Fprintf(&b, "\t\t\tcase r%d&end != 0:\n\t\t\t\te = %d\n", i, i)
		}
		b.WriteString("\t\t\t}\n\t\t\tdst = append(dst, [3]int{off + j, off + j + n, e})\n\t\t}\n\t}\n")
		for i := 0; i <= l; i++ {
			fmt.Fprintf(&b, "\tst[%d] = r%d\n", i, i)
		}
		b.WriteString("\treturn dst\n}\n")
	}

	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("scan_unrolled.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
}
