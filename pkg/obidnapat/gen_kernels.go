// gen_kernels writes scan_unrolled.go, scan_indel_unrolled.go, patternset_unrolled.go and
// patternset_il*.go, patternset_indel_unrolled.go (several words of the same levels in one loop): the search
// kernels of 1 to maxUnrolled error levels (0 to maxUnrolled for the packed
// words of a PatternSet), with the state of each level in a variable of its own (the
// compiler keeps them in registers). Run it with go generate.
//
// A variant without the allow mask, for the patterns that have no #, was tried
// and dropped: one operation less per level, but the arm64 compiler of Go 1.27
// then swaps two registers at each turn of the loop and lengthens the chain of
// dependencies, and the kernels came out 15 to 40 % slower.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
)

const maxUnrolled = 8

func main() {
	genCompiled()
	genWords()
	genInterleaved()
	genIndel()
	genIndelWords()
	genIndelInterleaved()
}

func write(name string, b *bytes.Buffer) {
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(name, src, 0o644); err != nil {
		log.Fatal(err)
	}
}

// genCompiled writes the kernels of a single pattern.
func genCompiled() {
	var b bytes.Buffer
	b.WriteString("// Code generated by gen_kernels.go; DO NOT EDIT.\n\npackage obidnapat\n\n")

	b.WriteString("// runUnrolled runs the kernel written out for the number of error levels of the\n")
	b.WriteString("// pattern; it reports false when there is none.\n")
	b.WriteString("func (c *compiled) runUnrolled(dst [][3]int, text []byte, base int, st *state) ([][3]int, bool) {\n\tswitch c.levels {\n")
	for l := 1; l <= maxUnrolled; l++ {
		fmt.Fprintf(&b, "\tcase %d:\n\t\treturn c.run%d(dst, text, base, st), true\n", l, l)
	}
	b.WriteString("\t}\n\treturn dst, false\n}\n")

	for l := 1; l <= maxUnrolled; l++ {
		fmt.Fprintf(&b, "\nfunc (c *compiled) run%d(dst [][3]int, text []byte, base int, st *state) [][3]int {\n", l)
		for i := 0; i <= l; i++ {
			fmt.Fprintf(&b, "\tr%d := st[%d]\n", i, i)
		}
		b.WriteString("\tm, end, allow, off, n := &c.mask, c.end, c.allow, c.offset(base), len(c.positions)\n")
		b.WriteString("\tfor j, b := range text {\n\t\tmk := m[b]\n")
		for i := l; i >= 1; i-- {
			fmt.Fprintf(&b, "\t\tr%d = (((r%d << 1) | 1) & mk) | (((r%d << 1) | 1) & allow)\n", i, i, i-1)
		}
		b.WriteString("\t\tr0 = ((r0 << 1) | 1) & mk\n")
		fmt.Fprintf(&b, "\t\tif r%d&end != 0 {\n\t\t\te := %d\n\t\t\tswitch {\n", l, l)
		for i := 0; i < l; i++ {
			fmt.Fprintf(&b, "\t\t\tcase r%d&end != 0:\n\t\t\t\te = %d\n", i, i)
		}
		b.WriteString("\t\t\t}\n\t\t\tdst = append(dst, [3]int{off + j, off + j + n, e})\n\t\t}\n\t}\n")
		for i := 0; i <= l; i++ {
			fmt.Fprintf(&b, "\tst[%d] = r%d\n", i, i)
		}
		b.WriteString("\treturn dst\n}\n")
	}

	write("scan_unrolled.go", &b)
}

// genWords writes the kernels of the packed words of a PatternSet: those of
// genCompiled, with the start bit of every core in place of 1, and the
// occurrences emitted by word.emit (which reads the levels from an array).
func genWords() {
	var b bytes.Buffer
	b.WriteString("// Code generated by gen_kernels.go; DO NOT EDIT.\n\npackage obidnapat\n\n")
	b.WriteString("// runUnrolled runs the kernel written out for the number of error levels of the\n")
	b.WriteString("// word; it reports false when there is none.\n")
	b.WriteString("func (w *word) runUnrolled(dst []Occurrence, text []byte, pos int, st *state, f *windows) ([]Occurrence, bool) {\n\tswitch w.levels {\n")
	for l := 0; l <= maxUnrolled; l++ {
		fmt.Fprintf(&b, "\tcase %d:\n\t\treturn w.run%d(dst, text, pos, st, f), true\n", l, l)
	}
	b.WriteString("\t}\n\treturn dst, false\n}\n")

	for l := 0; l <= maxUnrolled; l++ {
		fmt.Fprintf(&b, "\nfunc (w *word) run%d(dst []Occurrence, text []byte, pos int, st *state, f *windows) []Occurrence {\n", l)
		for i := 0; i <= l; i++ {
			fmt.Fprintf(&b, "\tr%d := st[%d]\n", i, i)
		}
		if l == 0 {
			b.WriteString("\tm, end, start := &w.mask, w.end, w.start\n")
		} else {
			b.WriteString("\tm, end, allow, start := &w.mask, w.end, w.allow, w.start\n")
		}
		b.WriteString("\tfor j, b := range text {\n\t\tmk := m[b]\n")
		for i := l; i >= 1; i-- {
			fmt.Fprintf(&b, "\t\tr%d = (((r%d << 1) | start) & mk) | (((r%d << 1) | start) & allow)\n", i, i, i-1)
		}
		b.WriteString("\t\tr0 = ((r0 << 1) | start) & mk\n")
		fmt.Fprintf(&b, "\t\tif hit := r%d & end; hit != 0 {\n", l)
		for i := 0; i <= l; i++ {
			fmt.Fprintf(&b, "\t\t\tst[%d] = r%d\n", i, i)
		}
		b.WriteString("\t\t\tdst = w.emit(dst, pos+j, hit, st, f)\n\t\t}\n\t}\n")
		for i := 0; i <= l; i++ {
			fmt.Fprintf(&b, "\tst[%d] = r%d\n", i, i)
		}
		b.WriteString("\treturn dst\n}\n")
	}
	write("patternset_unrolled.go", &b)
}

// maxBatch is the largest number of words advanced together (batches of 2 and
// maxBatch words are written); the loop carries one chain of dependencies per word,
// and the processor overlaps them (about 1.5 times faster with 2 words, 1.6 with 3).
const maxBatch = 3

// genInterleaved writes the kernels that advance k words of the same number of
// levels in one loop. Each state lives in variables named r<word>_<level>.
func genInterleaved() {
	head := "// Code generated by gen_kernels.go; DO NOT EDIT.\n\npackage obidnapat\n\n"
	var disp bytes.Buffer
	disp.WriteString(head)
	disp.WriteString("// runWords advances the words ws, all of the same number of levels, in one loop\n")
	disp.WriteString("// when a kernel is written for that many; it reports false when there is none.\n")
	disp.WriteString("func runWords(dst []Occurrence, text []byte, pos int, ws []*word, sts []*state, fs []*windows) ([]Occurrence, bool) {\n")
	disp.WriteString("\tswitch ws[0].levels {\n")
	for l := 0; l <= maxUnrolled; l++ {
		fmt.Fprintf(&disp, "\tcase %d:\n\t\tswitch len(ws) {\n", l)
		for k := 2; k <= maxBatch; k++ {
			fmt.Fprintf(&disp, "\t\tcase %d:\n\t\t\treturn run%dx%d(dst, text, pos, ws, sts, fs), true\n", k, l, k)
		}
		disp.WriteString("\t\t}\n")
	}
	disp.WriteString("\t}\n\treturn dst, false\n}\n")
	write("patternset_il.go", &disp)

	for k := 2; k <= maxBatch; k++ {
		for _, part := range [][2]int{{0, 4}, {5, maxUnrolled}} {
			var b bytes.Buffer
			b.WriteString(head)
			for l := part[0]; l <= part[1]; l++ {
				genBatch(&b, l, k)
			}
			write(fmt.Sprintf("patternset_il%d_%d.go", k, part[0]), &b)
		}
	}
}

func genBatch(b *bytes.Buffer, l, k int) {
	fmt.Fprintf(b, "\nfunc run%dx%d(dst []Occurrence, text []byte, pos int, ws []*word, sts []*state, fs []*windows) []Occurrence {\n", l, k)
	for w := 0; w < k; w++ {
		fmt.Fprintf(b, "\tw%d, s%d := ws[%d], sts[%d]\n", w, w, w, w)
		for i := 0; i <= l; i++ {
			fmt.Fprintf(b, "\tr%d_%d := s%d[%d]\n", w, i, w, i)
		}
		fmt.Fprintf(b, "\tm%d, e%d, st%d := &w%d.mask, w%d.end, w%d.start\n", w, w, w, w, w, w)
		if l > 0 {
			fmt.Fprintf(b, "\tal%d := w%d.allow\n", w, w)
		}
	}
	b.WriteString("\tfor j, c := range text {\n")
	for w := 0; w < k; w++ {
		fmt.Fprintf(b, "\t\tmk%d := m%d[c]\n", w, w)
	}
	for i := l; i >= 1; i-- {
		for w := 0; w < k; w++ {
			fmt.Fprintf(b, "\t\tr%d_%d = (((r%d_%d << 1) | st%d) & mk%d) | (((r%d_%d << 1) | st%d) & al%d)\n", w, i, w, i, w, w, w, i-1, w, w)
		}
	}
	for w := 0; w < k; w++ {
		fmt.Fprintf(b, "\t\tr%d_0 = ((r%d_0 << 1) | st%d) & mk%d\n", w, w, w, w)
	}
	cond := ""
	for w := 0; w < k; w++ {
		fmt.Fprintf(b, "\t\th%d := r%d_%d & e%d\n", w, w, l, w)
		if w > 0 {
			cond += " | "
		}
		cond += fmt.Sprintf("h%d", w)
	}
	fmt.Fprintf(b, "\t\tif %s != 0 {\n", cond)
	for w := 0; w < k; w++ {
		for i := 0; i <= l; i++ {
			fmt.Fprintf(b, "\t\t\ts%d[%d] = r%d_%d\n", w, i, w, i)
		}
	}
	for w := 0; w < k; w++ {
		fmt.Fprintf(b, "\t\t\tif h%d != 0 {\n\t\t\t\tdst = w%d.emit(dst, pos+j, h%d, s%d, fs[%d])\n\t\t\t}\n", w, w, w, w, w)
	}
	b.WriteString("\t\t}\n\t}\n")
	for w := 0; w < k; w++ {
		for i := 0; i <= l; i++ {
			fmt.Fprintf(b, "\ts%d[%d] = r%d_%d\n", w, i, w, i)
		}
	}
	b.WriteString("\treturn dst\n}\n")
}

// genIndel writes scan_indel_unrolled.go: the kernels with insertions and
// deletions (scan_indel.go) of 1 to maxUnrolled levels, the state of each level in
// a variable of its own.
func genIndel() {
	var b bytes.Buffer
	b.WriteString("// Code generated by gen_kernels.go; DO NOT EDIT.\n\npackage obidnapat\n\n")
	b.WriteString("// runIndelUnrolled runs the kernel written out for the number of error levels of\n")
	b.WriteString("// the pattern; it reports false when there is none.\n")
	b.WriteString("func (c *compiled) runIndelUnrolled(dst [][3]int, text []byte, base int, st *state) ([][3]int, bool) {\n\tswitch c.levels {\n")
	for l := 1; l <= maxUnrolled; l++ {
		fmt.Fprintf(&b, "\tcase %d:\n\t\treturn c.runIndel%d(dst, text, base, st), true\n", l, l)
	}
	b.WriteString("\t}\n\treturn dst, false\n}\n")

	for l := 1; l <= maxUnrolled; l++ {
		fmt.Fprintf(&b, "\nfunc (c *compiled) runIndel%d(dst [][3]int, text []byte, base int, st *state) [][3]int {\n", l)
		for i := 0; i <= l; i++ {
			fmt.Fprintf(&b, "\tr%d := st[%d]\n", i, i)
		}
		b.WriteString("\tm, end, allow, off, n := &c.mask, c.end, c.allow, c.offset(base), len(c.positions)\n")
		b.WriteString("\tfor j, b := range text {\n\t\tmk := m[b]\n")
		b.WriteString("\t\to0 := r0\n\t\tr0 = ((o0 << 1) | 1) & mk\n")
		for i := 1; i <= l; i++ {
			fmt.Fprintf(&b, "\t\to%d := r%d\n", i, i)
			fmt.Fprintf(&b, "\t\tr%d = (((o%d << 1) | 1) & mk) | ((o%d | (o%d << 1) | 1 | (r%d << 1)) & allow)\n", i, i, i-1, i-1, i-1)
		}
		fmt.Fprintf(&b, "\t\tif r%d&end != 0 {\n\t\t\te := %d\n\t\t\tswitch {\n", l, l)
		for i := 0; i < l; i++ {
			fmt.Fprintf(&b, "\t\t\tcase r%d&end != 0:\n\t\t\t\te = %d\n", i, i)
		}
		b.WriteString("\t\t\t}\n\t\t\tdst = append(dst, [3]int{off + j, off + j + n, e})\n\t\t}\n\t}\n")
		for i := 0; i <= l; i++ {
			fmt.Fprintf(&b, "\tst[%d] = r%d\n", i, i)
		}
		b.WriteString("\treturn dst\n}\n")
	}
	write("scan_indel_unrolled.go", &b)
}

