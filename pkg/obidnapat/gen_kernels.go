// genIndelInterleaved writes the kernels that advance k words with indels of the
// same number of levels in one loop (as genInterleaved does for the other
// words): patternset_indel_il.go for the dispatch, and the kernels in
// patternset_indel_il<k>_<first level>.go.
func genIndelInterleaved() {
	head := "// Code generated by gen_kernels.go; DO NOT EDIT.\n\npackage obidnapat\n\n"
	var disp bytes.Buffer
	disp.WriteString(head)
	disp.WriteString("// runIndelWords advances the words with indels ws, all of the same number of\n")
	disp.WriteString("// levels, in one loop when a kernel is written for that many; it reports false\n")
	disp.WriteString("// when there is none.\n")
	disp.WriteString("func runIndelWords(dst []Occurrence, text []byte, pos int, ws []*word, sts []*state, f *windows) ([]Occurrence, bool) {\n")
	disp.WriteString("\tswitch ws[0].levels {\n")
	for l := 1; l <= maxUnrolled; l++ {
		fmt.Fprintf(&disp, "\tcase %d:\n\t\tswitch len(ws) {\n", l)
		for k := 2; k <= maxBatch; k++ {
			fmt.Fprintf(&disp, "\t\tcase %d:\n\t\t\treturn runIndel%dx%d(dst, text, pos, ws, sts, f), true\n", k, l, k)
		}
		disp.WriteString("\t\t}\n")
	}
	disp.WriteString("\t}\n\treturn dst, false\n}\n")
	write("patternset_indel_il.go", &disp)

	for k := 2; k <= maxBatch; k++ {
		for _, part := range [][2]int{{1, 4}, {5, maxUnrolled}} {
			var b bytes.Buffer
			b.WriteString(head)
			for l := part[0]; l <= part[1]; l++ {
				genIndelBatch(&b, l, k)
			}
			write(fmt.Sprintf("patternset_indel_il%d_%d.go", k, part[0]), &b)
		}
	}
}

func genIndelBatch(b *bytes.Buffer, l, k int) {
	fmt.Fprintf(b, "\nfunc runIndel%dx%d(dst []Occurrence, text []byte, pos int, ws []*word, sts []*state, f *windows) []Occurrence {\n", l, k)
	for w := 0; w < k; w++ {
		fmt.Fprintf(b, "\tw%d, s%d := ws[%d], sts[%d]\n", w, w, w, w)
		for i := 0; i <= l; i++ {
			fmt.Fprintf(b, "\tr%d_%d := s%d[%d]\n", w, i, w, i)
		}
		fmt.Fprintf(b, "\tm%d, e%d, st%d, al%d := &w%d.mask, w%d.end, w%d.start, w%d.allow\n", w, w, w, w, w, w, w, w)
	}
	b.WriteString("\tfor j, c := range text {\n")
	for w := 0; w < k; w++ {
		fmt.Fprintf(b, "\t\tmk%d := m%d[c]\n", w, w)
	}
	for w := 0; w < k; w++ {
		fmt.Fprintf(b, "\t\to%d_0 := r%d_0\n\t\tr%d_0 = ((o%d_0 << 1) | st%d) & mk%d\n", w, w, w, w, w, w)
	}
	for i := 1; i <= l; i++ {
		for w := 0; w < k; w++ {
			fmt.Fprintf(b, "\t\to%d_%d := r%d_%d\n", w, i, w, i)
			fmt.Fprintf(b, "\t\tr%d_%d = (((o%d_%d << 1) | st%d) & mk%d) | ((o%d_%d | ((o%d_%d << 1) | st%d) | (r%d_%d << 1)) & al%d)\n",
				w, i, w, i, w, w, w, i-1, w, i-1, w, w, i-1, w)
		}
	}
	cond := ""
	for w := 0; w < k; w++ {
		fmt.Fprintf(b, "\t\th%d := r%d_%d & e%d\n", w, w, l, w)
		if w > 0 {
			cond += " | "
		}
		cond += fmt.Sprintf("h%d", w)
	}
	fmt.Fprintf(b, "\t\tif %s != 0 {\n", cond)
	for w := 0; w < k; w++ {
		for i := 0; i <= l; i++ {
			fmt.Fprintf(b, "\t\t\ts%d[%d] = r%d_%d\n", w, i, w, i)
		}
	}
	for w := 0; w < k; w++ {
		fmt.Fprintf(b, "\t\t\tif h%d != 0 {\n\t\t\t\tdst = w%d.emitIndel(dst, pos+j, h%d, s%d, f)\n\t\t\t}\n", w, w, w, w)
	}
	b.WriteString("\t\t}\n\t}\n")
	for w := 0; w < k; w++ {
		for i := 0; i <= l; i++ {
			fmt.Fprintf(b, "\ts%d[%d] = r%d_%d\n", w, i, w, i)
		}
	}
	b.WriteString("\treturn dst\n}\n")
}
