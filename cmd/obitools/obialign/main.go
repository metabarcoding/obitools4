package main

import (
	"os"

	"git.metabarcoding.org/obitools/obitools4/obitools4/pkg/obioptions"
	"git.metabarcoding.org/obitools/obitools4/obitools4/pkg/obitools/obialign"
	"git.metabarcoding.org/obitools/obitools4/obitools4/pkg/obitools/obiconvert"
	"git.metabarcoding.org/obitools/obitools4/obitools4/pkg/obiutils"
)

func main() {
	optionParser := obioptions.GenerateOptionParser(
		"obialign",
		"pairwise similarity of nucleotide sequences, as a CSV table (the principle of sumatra)",
		obialign.OptionSet)

	_, args := optionParser(os.Args)

	fs, err := obiconvert.CLIReadBioSequences(args...)
	obiconvert.OpenSequenceDataErrorMessage(args, err)

	obialign.CLIWriteTable(obialign.CLIOBIAlign(fs))

	obiutils.WaitForLastPipe()
}
